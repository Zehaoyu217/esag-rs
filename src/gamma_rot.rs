//! `γ`-rot: Yu & Huang's `γ` made smooth (`Shape::GammaRot`).
//!
//! # What is kept from `γ`
//!
//! * The layout of the coordinates: `γ ∈ ℝ^{(d−2)(d+1)/2}` in groups `G_j`
//!   (`j = 1..d−2`, `j + 1` entries). Group `j ≥ 2` places eigen-axis
//!   `j + 1` of the tangent covariance inside the first `j + 1` axes of the
//!   frame; group 1 is the first two axes.
//! * What a group means: how much variance its axis has against the axes
//!   below it, and where the axis points. `γ = 0` is the isotropic
//!   distribution.
//!
//! # The map
//!
//! Write `W` for the `(d−1) × (d−1)` covariance on the tangent space (unit
//! determinant) in the frame `Ξ(μ̂) = R(m → μ̂) E R_0` transported from a
//! reference direction `m` ([`crate::logtangent::LtFrame`]) and turned by a
//! fixed rotation `R_0` (the identity unless [`GrFrame::with_basis`]), so
//! that `V = Ξ W Ξᵀ + μ̂μ̂ᵀ`. `W` is built up one axis at a time:
//!
//! * **Group 1** is Paine et al.'s (2018) `γ` for `d = 3`:
//!   `W_2 = √(1 + ‖G_1‖²) I + [[G_{1,1}, G_{1,2}], [G_{1,2}, −G_{1,1}]]`,
//!   with eigenvalues `√(1 + r²) ± r` (`r = ‖G_1‖`) and the larger one's
//!   axis at angle `½ atan2(G_{1,2}, G_{1,1})`. Smooth, injective, and
//!   first-order identifiable at isotropy, because the axis enters through
//!   its doubled angle. At `d = 3` the parameterization is therefore the
//!   original ESAG one (in the transported frame).
//! * **Group `j ≥ 2`** is read as `(κ_j, ω_j) ∈ ℝ × ℝ^j`:
//!   `W_{j+1} = e^{−κ_j/(j+1)} Q_j (W_j ⊕ e^{κ_j}) Q_jᵀ`. So `e^{κ_j}` is the
//!   variance of the new axis against the geometric mean of the variances
//!   of the axes below it (`κ_j = 0`: the block's typical variance; `κ_j`
//!   signed, so eigenvalues cross freely as `x` varies), and
//!   `Q_j = I + a(s²) Ω + b(s²) Ω²` is the minimal rotation of the block
//!   taking its pole `e_{j+1}` to the axis `v_j = Q_j e_{j+1}`, generated by
//!   the rotation vector `ω_j` (`Ω e_{j+1} = (ω_j, 0)`, `s = ‖ω_j‖`). Its
//!   other columns, the lower axes, are the parallel transport of
//!   `e_1..e_j` along that great circle. Two links: [`RotLink::Stereo`],
//!   `a = 4/(4 + s²)`, `b = 2/(4 + s²)` (the Cayley transform: `v_j` is the
//!   inverse stereographic image of `ω_j/2`, the rotation angle is
//!   `2 atan(s/2) < π`, and every entry of `W` is rational in `ω_j`); and
//!   [`RotLink::Exp`], `a = sin s/s`, `b = (1 − cos s)/s²` (the exponential
//!   map: angle `s`, periodic).
//!
//! The log-eigenvalues are explicit: with `c = Σ_{i≥2} κ_i/(i+1)`,
//! `log λ_{1,2} = ∓ asinh r − c` and
//! `log λ_{j+1} = κ_j · j/(j+1) − Σ_{i>j} κ_i/(i+1)`, which sum to 0.
//!
//! # Why
//!
//! `γ ↦ V` is discontinuous where a group's trailing pair vanishes and
//! where a group `j ≥ 2` vanishes above unequal lower eigenvalues
//! (`docs/MATH.md` §2), and not differentiable at any zero group. Both come
//! from reading a group as a norm and a direction and completing the
//! direction's frame by plane rotations whose angles divide by that norm.
//! Here nothing divides by a norm: the map is `C^∞` on all of `ℝ^{d} ×
//! ℝ^{(d−2)(d+1)/2}`, so a regression `γ(x) = Γ x̃` has a likelihood without
//! cliffs and without `γ`'s non-regular suprema. A zero group is an ordinary
//! point (the new axis then has the block's geometric-mean variance, not a
//! tie), so penalties that zero a group land on regular points. What
//! remains is non-identifiability, not discontinuity: a flat direction at
//! each exact tie of two eigenvalues (the rotation within the tied plane),
//! and every `ω_j` flat at exact isotropy (the information is singular
//! there, as in every chart made of eigenvalues and eigenvectors; group 1
//! is the exception). The map is not injective either: the sign of an axis
//! (`v_j ↦ −v_j`), the labelling of the eigenvalues and, for `Exp`,
//! `s ↦ s + 2π` give the same `V` from other coordinates. That is a discrete
//! gauge; [`GrFrame::coords_from_covariance`] returns the canonical member
//! (eigenvalues ascending along the axes, `v_j · e_{j+1} ≥ 0`).
//!
//! Without covariates the family of distributions is `γ`'s (every `V` has
//! coordinates). With covariates it is a different regression model: an
//! axis moves along a great circle at a constant rate in `x` and a
//! log-variance ratio is affine in `x`, where `γ` takes the polar
//! coordinates of an affine function. The basis rotation `R_0` matters for
//! the same reason the reference `m` does: with `R_0` the eigenframe of a
//! pilot estimate at the mean design row, every axis starts at its pole
//! (`ω_j = 0`) and the rotations the regression describes are small near
//! the data's centre.
//!
//! [`loglik_gr`] is the generic (forward-mode capable) kernel;
//! [`loglik_gr_grad`] the gradient and [`loglik_gr_hess_fd`] the Hessian by
//! differences, both in forward mode. The reverse-mode gradient and the
//! exact Hessian are in [`crate::gamma_rot_adjoint`].

