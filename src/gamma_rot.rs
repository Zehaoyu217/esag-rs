    fn unit(v: &mut [f64]) {
        let n = v.iter().map(|x| x * x).sum::<f64>().sqrt();
        v.iter_mut().for_each(|x| *x /= n);
    }

    fn reference(d: usize, rng: &mut ChaCha8Rng) -> Vec<f64> {
        let mut m: Vec<f64> = (0..d).map(|_| rng.random_range(-1.0..1.0)).collect();
        unit(&mut m);
        m
    }

    /// Random coordinates: `‖G_1‖ ≤ √2`, `|κ_j| ≤ 1`, `‖ω_j‖ ≤ wmax`.
    fn coords(d: usize, wmax: f64, rng: &mut ChaCha8Rng) -> Vec<f64> {
        let mut g = vec![0.0; dims::gamma_len(d)];
        g[0] = rng.random_range(-1.0..1.0);
        g[1] = rng.random_range(-1.0..1.0);
        for gr in 2..=d - 2 {
            let off = gr * (gr + 1) / 2 - 1;
            g[off] = rng.random_range(-1.0..1.0);
            let mut w: Vec<f64> = (0..gr).map(|_| rng.random_range(-1.0..1.0)).collect();
            unit(&mut w);
            let s = rng.random_range(0.0..wmax);
            for i in 0..gr {
                g[off + 1 + i] = s * w[i];
            }
        }
        g
    }

    fn mu(d: usize, rng: &mut ChaCha8Rng) -> Vec<f64> {
        let mut m = reference(d, rng);
        let k = rng.random_range(0.5..4.0);
        m.iter_mut().for_each(|x| *x *= k);
        m
    }

    /// A random rotation of `ℝ^p` (QR of a Gaussian matrix, determinant +1).
    fn rotation(p: usize, rng: &mut ChaCha8Rng) -> DMatrix<f64> {
        let a = DMatrix::from_fn(p, p, |_, _| rng.random_range(-1.0..1.0));
        let mut q = a.qr().q();
        if q.determinant() < 0.0 {
            for r in 0..p {
                q[(r, 0)] = -q[(r, 0)];
            }
        }
        q
    }

    fn max_abs_diff(a: &DMatrix<f64>, b: &DMatrix<f64>) -> f64 {
        (a - b).iter().map(|x| x.abs()).fold(0.0, f64::max)
    }

    /// `V` is a valid ESAG covariance (`V μ̂ = μ̂`, `det V = 1`), its tangent
    /// eigenvalues are the explicit log-eigenvalues, and
    /// `coords → V → coords → V` returns the same `V`, for `d = 3..=10`, both
    /// links, with and without a basis rotation.
    #[test]
    fn covariance_roundtrip() {
        let mut rng = ChaCha8Rng::seed_from_u64(7);
        for link in [RotLink::Stereo, RotLink::Exp] {
            for d in 3..=10 {
                for turned in [false, true] {
                    let mut fr = GrFrame::new(&reference(d, &mut rng), link);
                    if turned {
                        fr = fr.with_basis(&rotation(d - 1, &mut rng));
                    }
                    for _ in 0..3 {
                        let m = mu(d, &mut rng);
                        let g = coords(d, 3.0, &mut rng);
                        let v = fr.covariance(&m, &g);
                        let mh: Vec<f64> = {
                            let n = m.iter().map(|x| x * x).sum::<f64>().sqrt();
                            m.iter().map(|x| x / n).collect()
                        };
                        for r in 0..d {
                            let vm: f64 = (0..d).map(|c| v[(r, c)] * mh[c]).sum();
                            assert!((vm - mh[r]).abs() < 1e-10, "V μ̂ ≠ μ̂ at d={d}");
                        }
                        assert!(
                            (v.determinant() - 1.0).abs() < 1e-8,
                            "det V = {}",
                            v.determinant()
                        );
                        let w = fr.tangent_covariance(&g);
                        let mut ev: Vec<f64> = nalgebra::SymmetricEigen::new(w.clone())
                            .eigenvalues
                            .iter()
                            .map(|l| l.ln())
                            .collect();
                        ev.sort_by(f64::total_cmp);
                        let mut ex = fr.log_eigenvalues(&g);
                        ex.sort_by(f64::total_cmp);
                        for (a, b) in ev.iter().zip(&ex) {
                            assert!((a - b).abs() < 1e-9, "log-eigenvalues {ev:?} vs {ex:?}");
                        }
                        let g2 = fr.coords_from_covariance(&m, &v);
                        let v2 = fr.covariance(&m, &g2);
                        assert!(
                            max_abs_diff(&v, &v2) < 1e-8,
                            "d={d} {link:?} turned={turned}: V differs by {}",
                            max_abs_diff(&v, &v2)
                        );
                        let l2 = fr.log_eigenvalues(&g2);
                        for k in 1..d - 1 {
                            assert!(l2[k] >= l2[k - 1] - 1e-9, "{l2:?}");
                        }
                        for gr in 2..=d - 2 {
                            let a = fr.axis(&g2, gr);
                            assert!(a[gr] >= -1e-12);
                        }
                    }
                }
            }
        }
    }

    /// Coordinates in the canonical gauge roundtrip exactly.
    #[test]
    fn coordinates_roundtrip_in_the_canonical_gauge() {
        let mut rng = ChaCha8Rng::seed_from_u64(11);
        for link in [RotLink::Stereo, RotLink::Exp] {
            for d in 4..=8 {
                let fr = GrFrame::new(&reference(d, &mut rng), link);
                let m = mu(d, &mut rng);
                let mut g = coords(d, 1.2, &mut rng);
                // ascending eigenvalues: each κ_j above log λ_j − mean of the
                // lower log-eigenvalues, with a margin
                for gr in 2..=d - 2 {
                    let off = gr * (gr + 1) / 2 - 1;
                    let extra = g[off].abs();
                    g[off] = 0.0;
                    let l = fr.log_eigenvalues(&g);
                    let lower_mean = l[..gr].iter().sum::<f64>() / gr as f64;
                    g[off] = l[gr - 1] - lower_mean + 0.05 + extra;
                }
                let v = fr.covariance(&m, &g);
                let g2 = fr.coords_from_covariance(&m, &v);
                for (a, b) in g.iter().zip(&g2) {
                    assert!((a - b).abs() < 1e-7, "{link:?} d={d}: {g:?} vs {g2:?}");
                }
            }
        }
    }

    /// The kernel's log-density equals the ESAG log-density of the
    /// covariance it parameterizes, at every `d`, with a basis rotation too.
    #[test]
    fn kernel_matches_the_covariance() {
        let mut rng = ChaCha8Rng::seed_from_u64(3);
        for link in [RotLink::Stereo, RotLink::Exp] {
            for d in 3..=10 {
                for turned in [false, true] {
                    let mut fr = GrFrame::new(&reference(d, &mut rng), link);
                    if turned {
                        fr = fr.with_basis(&rotation(d - 1, &mut rng));
                    }
                    for _ in 0..4 {
                        let m = mu(d, &mut rng);
                        let g = coords(d, 2.0, &mut rng);
                        let mut eta = m.clone();
                        eta.extend(g.iter());
                        let mut y = reference(d, &mut rng);
                        unit(&mut y);
                        let a = loglik_gr::<f64>(&fr, &eta, &y);
                        let v = fr.covariance(&m, &g);
                        let dist = crate::distribution::Esag::from_covariance(&m, &v).unwrap();
                        let b = dist.log_pdf(&y);
                        assert!((a - b).abs() < 1e-9, "d={d} {link:?}: {a} vs {b}");
                    }
                }
            }
        }
    }

    /// At `d = 3` the map is Paine et al.'s `γ`: tangent eigenvalues
    /// `√(1 + r²) ± r`, the larger one's axis at angle `½ atan2(γ_2, γ_1)`.
    #[test]
    fn d3_is_paine() {
        let mut rng = ChaCha8Rng::seed_from_u64(5);
        let fr = GrFrame::stereo(&reference(3, &mut rng));
        for _ in 0..10 {
            let g = coords(3, 0.0, &mut rng);
            let r = (g[0] * g[0] + g[1] * g[1]).sqrt();
            let w = fr.tangent_covariance(&g);
            let eig = nalgebra::SymmetricEigen::new(w);
            let (i_hi, i_lo) = if eig.eigenvalues[0] > eig.eigenvalues[1] {
                (0, 1)
            } else {
                (1, 0)
            };
            let s = (1.0 + r * r).sqrt();
            assert!((eig.eigenvalues[i_hi] - (s + r)).abs() < 1e-12);
            assert!((eig.eigenvalues[i_lo] - (s - r)).abs() < 1e-12);
            let psi = 0.5 * g[1].atan2(g[0]);
            let (c, sn) = (eig.eigenvectors[(0, i_hi)], eig.eigenvectors[(1, i_hi)]);
            let cross = (c * psi.sin() - sn * psi.cos()).abs();
            assert!(cross < 1e-10, "axis angle off by {cross}");
        }
    }

    fn fd_grad(fr: &GrFrame, eta: &[f64], y: &[f64]) -> Vec<f64> {
        let h = 1e-6;
        (0..eta.len())
            .map(|k| {
                let mut ep = eta.to_vec();
                let mut em = eta.to_vec();
                ep[k] += h;
                em[k] -= h;
                (loglik_gr::<f64>(fr, &ep, y) - loglik_gr::<f64>(fr, &em, y)) / (2.0 * h)
            })
            .collect()
    }

    /// The forward-mode gradient matches central differences, including at
    /// the points where `γ` is singular: group 1 zero (isotropic 2-block),
    /// a group's rotation vector zero (the pole), a zero log-ratio, and for
    /// `Exp` a rotation by exactly `π` (the antipode).
    #[test]
    fn gradient_matches_differences_at_the_special_points() {
        let mut rng = ChaCha8Rng::seed_from_u64(5);
        for link in [RotLink::Stereo, RotLink::Exp] {
            for d in [4usize, 5, 6, 8] {
                let fr = GrFrame::new(&reference(d, &mut rng), link)
                    .with_basis(&rotation(d - 1, &mut rng));
                let base: Vec<f64> = {
                    let mut e = mu(d, &mut rng);
                    e.extend(coords(d, 1.5, &mut rng));
                    e
                };
                let off2 = d + 2; // group 2 starts at γ index 2
                let mut points = vec![base.clone()];
                let mut g1 = base.clone();
                g1[d] = 0.0;
                g1[d + 1] = 0.0;
                points.push(g1);
                let mut pole = base.clone();
                for i in 0..2 {
                    pole[off2 + 1 + i] = 0.0;
                }
                points.push(pole);
                let mut zero = base.clone();
                zero[off2] = 0.0;
                points.push(zero);
                if link == RotLink::Exp {
                    let mut anti = base.clone();
                    let w = &mut anti[off2 + 1..off2 + 3];
                    let s = (w[0] * w[0] + w[1] * w[1]).sqrt();
                    w[0] *= std::f64::consts::PI / s;
                    w[1] *= std::f64::consts::PI / s;
                    points.push(anti);
                }
                for eta in &points {
                    let mut y = reference(d, &mut rng);
                    unit(&mut y);
                    let mut g = vec![0.0; eta.len()];
                    let f = loglik_gr_grad(&fr, eta, &y, &mut g);
                    assert!(f.is_finite());
                    let fd = fd_grad(&fr, eta, &y);
                    for k in 0..eta.len() {
                        let tol = 1e-5 * (1.0 + g[k].abs());
                        assert!(
                            (g[k] - fd[k]).abs() < tol,
                            "{link:?} d={d} k={k}: dual {} vs fd {}",
                            g[k],
                            fd[k]
                        );
                    }
                }
            }
        }
    }

    /// The Hessian by differences is symmetric and matches differences of
    /// the gradient taken with another step.
    #[test]
    fn hessian_differences_are_consistent() {
        let mut rng = ChaCha8Rng::seed_from_u64(17);
        let d = 5;
        let fr = GrFrame::stereo(&reference(d, &mut rng));
        let mut eta = mu(d, &mut rng);
        eta.extend(coords(d, 1.0, &mut rng));
        let mut y = reference(d, &mut rng);
        unit(&mut y);
        let n = eta.len();
        let (mut g, mut h) = (vec![0.0; n], vec![0.0; n * n]);
        loglik_gr_hess_fd(&fr, &eta, &y, &mut g, &mut h);
        for i in 0..n {
            for j in 0..n {
                assert!((h[i * n + j] - h[j * n + i]).abs() < 1e-12);
            }
        }
        let step = 1e-4;
        for i in 0..n {
            let mut ep = eta.clone();
            let mut em = eta.clone();
            ep[i] += step;
            em[i] -= step;
            let (mut gp, mut gm) = (vec![0.0; n], vec![0.0; n]);
            loglik_gr_grad(&fr, &ep, &y, &mut gp);
            loglik_gr_grad(&fr, &em, &y, &mut gm);
            for j in 0..n {
                let hd = (gp[j] - gm[j]) / (2.0 * step);
                assert!(
                    (hd - h[i * n + j]).abs() < 1e-4 * (1.0 + hd.abs()),
                    "H[{i},{j}] {} vs {hd}",
                    h[i * n + j]
                );
            }
        }
    }

    /// The gradient is continuous through the antipode (`Exp`, `‖ω_2‖ = π`),
    /// through the pole (`ω_2 = 0`) and through group 1's zero: a kink would
    /// change it by O(1).
    #[test]
    fn gradient_is_continuous_through_the_special_points() {
        let mut rng = ChaCha8Rng::seed_from_u64(9);
        let d = 5;
        for link in [RotLink::Stereo, RotLink::Exp] {
            let fr = GrFrame::new(&reference(d, &mut rng), link);
            let mut eta = mu(d, &mut rng);
            eta.extend(coords(d, 1.0, &mut rng));
            let mut y = reference(d, &mut rng);
            unit(&mut y);
            let off2 = d + 2;
            let h = 1e-4;
            let jump = |set: &dyn Fn(&mut Vec<f64>, f64)| -> f64 {
                let mut grads = vec![];
                for t in [-h, h] {
                    let mut e = eta.clone();
                    set(&mut e, t);
                    let mut g = vec![0.0; e.len()];
                    loglik_gr_grad(&fr, &e, &y, &mut g);
                    grads.push(g);
                }
                grads[0]
                    .iter()
                    .zip(&grads[1])
                    .map(|(a, b)| (a - b).abs())
                    .fold(0.0, f64::max)
            };
            let mut radii = vec![0.0];
            if link == RotLink::Exp {
                radii.push(std::f64::consts::PI);
            }
            for r0 in radii {
                let j = jump(&|e: &mut Vec<f64>, t: f64| {
                    e[off2 + 1] = (r0 + t) * 0.6;
                    e[off2 + 2] = (r0 + t) * 0.8;
                });
                assert!(j < 1e-2, "{link:?} radius {r0}: gradient jumps by {j}");
            }
            let j = jump(&|e: &mut Vec<f64>, t: f64| {
                e[d] = t * 0.6;
                e[d + 1] = t * 0.8;
            });
            assert!(j < 1e-2, "{link:?} group 1 zero: gradient jumps by {j}");
        }
    }

    /// The Jacobian of `coords ↦ W` has full rank at a generic point and at
    /// a zero group (`κ_2 = 0`, `ω_2 = 0`), and drops rank by one at an
    /// exact tie of two eigenvalues.
    #[test]
    fn jacobian_rank() {
        let mut rng = ChaCha8Rng::seed_from_u64(13);
        let d = 5;
        let p = d - 1;
        let fr = GrFrame::stereo(&reference(d, &mut rng));
        let jac = |g: &[f64]| -> DMatrix<f64> {
            let h = 1e-6;
            let ng = g.len();
            let mut j = DMatrix::zeros(p * (p + 1) / 2, ng);
            for k in 0..ng {
                let mut gp = g.to_vec();
                let mut gm = g.to_vec();
                gp[k] += h;
                gm[k] -= h;
                let wp = fr.tangent_covariance(&gp);
                let wm = fr.tangent_covariance(&gm);
                let mut r = 0;
                for a in 0..p {
                    for b in a..p {
                        j[(r, k)] = (wp[(a, b)] - wm[(a, b)]) / (2.0 * h);
                        r += 1;
                    }
                }
            }
            j
        };
        let sorted = |m: DMatrix<f64>| -> Vec<f64> {
            let mut s: Vec<f64> = m.singular_values().iter().copied().collect();
            s.sort_by(f64::total_cmp);
            s
        };
        let g = coords(d, 1.0, &mut rng);
        let s = sorted(jac(&g));
        assert!(s[0] > 1e-4 * s[s.len() - 1], "generic point: {s:?}");
        let mut zero = g.clone();
        zero[2] = 0.0;
        zero[3] = 0.0;
        zero[4] = 0.0;
        let s = sorted(jac(&zero));
        assert!(s[0] > 1e-4 * s[s.len() - 1], "zero group: {s:?}");
        // a tie λ_3 = λ_2: κ_2 = log λ_2 − mean(log λ_1, log λ_2) = asinh r
        let mut tie = g.clone();
        let r = (g[0] * g[0] + g[1] * g[1]).sqrt();
        tie[2] = r.asinh();
        let s = sorted(jac(&tie));
        assert!(s[0] < 1e-6 * s[s.len() - 1], "tie: {s:?}");
        assert!(s[1] > 1e-4 * s[s.len() - 1], "tie: {s:?}");
    }
