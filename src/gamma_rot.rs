/// How a group's rotation vector `ω_j` turns the block's pole into its axis.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum RotLink {
    /// Cayley transform: rotation angle `2 atan(‖ω‖/2) < π`, rational, no wrap.
    Stereo,
    /// Exponential map: rotation angle `‖ω‖`, periodic.
    Exp,
}

/// The `γ`-rot parameterization: a reference mean direction, a link and an
/// optional rotation of the tangent basis.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct GrFrame {
    lt: LtFrame,
    link: RotLink,
    /// `R_0`, `(d−1) × (d−1)` row-major (`None`: identity).
    #[serde(default)]
    r0: Option<Vec<f64>>,
}

impl GrFrame {
    /// Frame with reference mean direction `m` (normalised) and link `link`.
    ///
    /// # Panics
    /// If `m.len() < 3` or `m` is zero.
    pub fn new(m: &[f64], link: RotLink) -> Self {
        assert!(m.len() >= 3, "gamma-rot needs d >= 3, got d = {}", m.len());
        Self {
            lt: LtFrame::new(m),
            link,
            r0: None,
        }
    }

    /// The default link ([`RotLink::Stereo`]) with reference `m`.
    pub fn stereo(m: &[f64]) -> Self {
        Self::new(m, RotLink::Stereo)
    }

    /// Turn the tangent basis by the rotation `r0` (`(d−1) × (d−1)`,
    /// orthogonal): the axes of the map are then the columns of `E R_0`
    /// transported to `μ̂`.
    ///
    /// # Panics
    /// If `r0` is not `(d−1) × (d−1)`.
    pub fn with_basis(mut self, r0: &DMatrix<f64>) -> Self {
        let p = self.dim() - 1;
        assert!(
            r0.nrows() == p && r0.ncols() == p,
            "the basis rotation must be {p} × {p}"
        );
        self.r0 = Some(
            (0..p)
                .flat_map(|r| (0..p).map(move |c| (r, c)))
                .map(|(r, c)| r0[(r, c)])
                .collect(),
        );
        self
    }

    /// The dimension `d`.
    pub fn dim(&self) -> usize {
        self.lt.dim()
    }

    /// The link.
    pub fn link(&self) -> RotLink {
        self.link
    }

    /// The tangent frame (reference mean direction `m` and basis `E`).
    pub fn lt_frame(&self) -> &LtFrame {
        &self.lt
    }

    /// `R_0` row-major (`(d−1) × (d−1)`), `None` for the identity.
    #[inline]
    pub(crate) fn r0_slice(&self) -> Option<&[f64]> {
        self.r0.as_deref()
    }

    /// The basis rotation `R_0` (`None`: identity).
    pub fn basis(&self) -> Option<DMatrix<f64>> {
        let p = self.dim() - 1;
        self.r0.as_ref().map(|r| DMatrix::from_row_slice(p, p, r))
    }

    /// `Ξ(μ̂) R_0`, `d × (d−1)`.
    pub fn tangent_frame(&self, mu: &[f64]) -> DMatrix<f64> {
        let d = self.dim();
        let mut xi = DMatrix::zeros(d, d - 1);
        let (mut z, mut u) = (vec![0.0; d], vec![0.0; d]);
        let mut y = vec![0.0; d];
        for i in 0..d {
            y.iter_mut().for_each(|v| *v = 0.0);
            y[i] = 1.0;
            project(&self.lt, mu, &y, &mut z, &mut u);
            turn(self, &mut z);
            for j in 0..d - 1 {
                xi[(i, j)] = z[j];
            }
        }
        xi
    }

    /// Log-eigenvalues of the tangent covariance along the axes
    /// (`λ_1 ≤ λ_2` from group 1, `λ_{j+1}` from group `j`), summing to 0.
    pub fn log_eigenvalues(&self, gamma: &[f64]) -> Vec<f64> {
        let d = self.dim();
        assert_eq!(
            gamma.len(),
            dims::gamma_len(d),
            "gamma has length {}",
            gamma.len()
        );
        let mut ell = vec![0.0; d - 1];
        log_eigen(gamma, d, &mut ell);
        ell
    }

    /// Eigenvalues `λ_1..λ_{d−1}` of the tangent covariance (product 1), in
    /// the order of [`GrFrame::log_eigenvalues`].
    pub fn eigenvalues(&self, gamma: &[f64]) -> Vec<f64> {
        self.log_eigenvalues(gamma)
            .iter()
            .map(|l| l.exp())
            .collect()
    }

    /// The axis `v_j = Q_j e_{j+1}` of group `gr ≥ 2`, in the coordinates of
    /// its block (length `gr + 1`).
    pub fn axis(&self, gamma: &[f64], gr: usize) -> Vec<f64> {
        assert!(gr >= 2, "group {gr} has no rotation vector");
        let off = gr * (gr + 1) / 2 - 1;
        let w = &gamma[off + 1..off + gr + 1];
        let s2: f64 = w.iter().map(|x| x * x).sum();
        let (a, b) = link_coeffs(self.link, s2);
        let mut v: Vec<f64> = w.iter().map(|x| a * x).collect();
        v.push(1.0 - b * s2);
        v
    }

    /// The tangent covariance `W` (`(d−1) × (d−1)`, determinant 1) in the
    /// frame `Ξ(μ̂) R_0`.
    pub fn tangent_covariance(&self, gamma: &[f64]) -> DMatrix<f64> {
        let d = self.dim();
        assert_eq!(
            gamma.len(),
            dims::gamma_len(d),
            "gamma has length {}",
            gamma.len()
        );
        let p = d - 1;
        let mut w = DMatrix::zeros(p, p);
        let r = (gamma[0] * gamma[0] + gamma[1] * gamma[1]).sqrt();
        let s = (1.0 + r * r).sqrt();
        w[(0, 0)] = s + gamma[0];
        w[(1, 1)] = s - gamma[0];
        w[(0, 1)] = gamma[1];
        w[(1, 0)] = gamma[1];
        for gr in 2..=d - 2 {
            let off = gr * (gr + 1) / 2 - 1;
            let kappa = gamma[off];
            let om = &gamma[off + 1..off + gr + 1];
            let n = gr + 1;
            w[(gr, gr)] = kappa.exp();
            // W ← Q W Qᵀ on the leading n × n block, then the scale
            let mut col = vec![0.0; n];
            for c in 0..n {
                for rr in 0..n {
                    col[rr] = w[(rr, c)];
                }
                rotate(self.link, gr, om, &mut col);
                for rr in 0..n {
                    w[(rr, c)] = col[rr];
                }
            }
            for rr in 0..n {
                for c in 0..n {
                    col[c] = w[(rr, c)];
                }
                rotate(self.link, gr, om, &mut col);
                for c in 0..n {
                    w[(rr, c)] = col[c];
                }
            }
            let sc = (-kappa / n as f64).exp();
            for rr in 0..n {
                for c in 0..n {
                    w[(rr, c)] *= sc;
                }
            }
        }
        w
    }

    /// The covariance `V` of `ESAG(mu, γ)` in this parameterization.
    pub fn covariance(&self, mu: &[f64], gamma: &[f64]) -> DMatrix<f64> {
        let d = self.dim();
        assert_eq!(mu.len(), d, "mu has length {}", mu.len());
        let xi = self.tangent_frame(mu);
        let w = self.tangent_covariance(gamma);
        let nm = mu.iter().map(|x| x * x).sum::<f64>().sqrt();
        let mh: Vec<f64> = if nm > 0.0 {
            mu.iter().map(|x| x / nm).collect()
        } else {
            self.lt.reference().to_vec()
        };
        let mut v = &xi * w * xi.transpose();
        for r in 0..d {
            for c in 0..d {
                v[(r, c)] += mh[r] * mh[c];
            }
        }
        v
    }

    /// Coordinates of `(mu, v)` in this parameterization (`v` scaled to
    /// determinant 1 on the tangent space): the canonical member of the
    /// equivalence class, with eigenvalues ascending along the axes and
    /// every axis in the hemisphere of its pole (`v_j · e_{j+1} ≥ 0`; for
    /// `Stereo` then `‖ω_j‖ ≤ 2`, for `Exp` `‖ω_j‖ ≤ π/2`).
    pub fn coords_from_covariance(&self, mu: &[f64], v: &DMatrix<f64>) -> Vec<f64> {
        let xi = self.tangent_frame(mu);
        let (lam, cur) = sorted_tangent_eigen(&xi, v);
        self.coords_from_eigen(&lam, cur)
    }

    /// [`GrFrame::coords_from_covariance`] from the tangent eigenvalues
    /// `lam` (product 1) and eigenvectors `cur` (columns, in the frame's
    /// coordinates), in the given order: axis `k` gets `lam[k]`. Each axis
    /// is turned into the hemisphere of its pole.
    pub fn coords_from_eigen(&self, lam: &[f64], cur: DMatrix<f64>) -> Vec<f64> {
        self.coords_from_eigen_with(lam, cur, true)
    }

    /// [`GrFrame::coords_from_eigen`] keeping the signs of the given
    /// eigenvectors (so that coordinates of neighbouring `V`s, labelled and
    /// signed consistently by the caller, vary continuously): an axis more
    /// than 90° from its pole then has `‖ω_j‖ > 2` (`Stereo`).
    pub fn coords_from_eigen_signed(&self, lam: &[f64], cur: DMatrix<f64>) -> Vec<f64> {
        self.coords_from_eigen_with(lam, cur, false)
    }

    fn coords_from_eigen_with(
        &self,
        lam: &[f64],
        mut cur: DMatrix<f64>,
        canonical: bool,
    ) -> Vec<f64> {
        let d = self.dim();
        let mut gamma = vec![0.0; dims::gamma_len(d)];
        let logs: Vec<f64> = lam.iter().map(|l| l.ln()).collect();
        for gr in (2..=d - 2).rev() {
            let off = gr * (gr + 1) / 2 - 1;
            let mut a: Vec<f64> = (0..=gr).map(|i| cur[(i, gr)]).collect();
            let na = a.iter().map(|x| x * x).sum::<f64>().sqrt();
            a.iter_mut().for_each(|x| *x /= na);
            if canonical && a[gr] < 0.0 {
                a.iter_mut().for_each(|x| *x = -*x);
            }
            let omega: Vec<f64> = match self.link {
                RotLink::Stereo => (0..gr).map(|i| 2.0 * a[i] / (1.0 + a[gr])).collect(),
                RotLink::Exp => {
                    let sn = (0..gr).map(|i| a[i] * a[i]).sum::<f64>().sqrt();
                    let th = a[gr].clamp(-1.0, 1.0).acos();
                    if sn < 1e-300 {
                        vec![0.0; gr]
                    } else {
                        (0..gr).map(|i| th * a[i] / sn).collect()
                    }
                }
            };
            // κ: the new axis against the geometric mean of the lower axes
            let lower_mean = logs[..gr].iter().sum::<f64>() / gr as f64;
            gamma[off] = logs[gr] - lower_mean;
            gamma[off + 1..off + gr + 1].copy_from_slice(&omega);
            for l in 0..gr {
                let mut col: Vec<f64> = (0..=gr).map(|i| cur[(i, l)]).collect();
                rotate_t(self.link, gr, &omega, &mut col);
                for i in 0..=gr {
                    cur[(i, l)] = col[i];
                }
            }
        }
        // group 1: Paine's γ from the 2-block, r = sinh(½ log(λ_2/λ_1)),
        // doubled angle of the axis of λ_2
        let r = (0.5 * (logs[1] - logs[0])).sinh();
        let (c, s) = (cur[(0, 1)], cur[(1, 1)]);
        let nn = (c * c + s * s).sqrt();
        let (c, s) = (c / nn, s / nn);
        gamma[0] = r * (c * c - s * s);
        gamma[1] = r * (2.0 * c * s);
        gamma
    }
}

/// `z ← R_0ᵀ z` on the first `d − 1` entries (identity without a basis).
#[inline(always)]
fn turn<S: Scalar>(fr: &GrFrame, z: &mut [S]) {
    if let Some(r0) = &fr.r0 {
        let p = fr.dim() - 1;
        let mut out = [S::zero(); 16];
        assert!(p <= 16, "basis rotations are implemented for d <= 17");
        for j in 0..p {
            let mut acc = S::zero();
            for i in 0..p {
                acc += z[i] * r0[i * p + j];
            }
            out[j] = acc;
        }
        z[..p].copy_from_slice(&out[..p]);
    }
}

/// `(a, b)` of `Q = I + a Ω + b Ω²` for `s² = ‖ω‖²`.
#[inline(always)]
fn link_coeffs<S: Scalar>(link: RotLink, s2: S) -> (S, S) {
    match link {
        RotLink::Stereo => {
            let den = s2 + 4.0;
            (S::from_f64(4.0) / den, S::from_f64(2.0) / den)
        }
        RotLink::Exp => {
            if s2.re() < 1e-10 {
                (
                    S::one() - s2 * (1.0 / 6.0),
                    S::from_f64(0.5) - s2 * (1.0 / 24.0),
                )
            } else {
                let s = s2.sqrt();
                (s.sin() / s, (S::one() - s.cos()) / s2)
            }
        }
    }
}

/// `x ← Q_jᵀ x` on the first `gr + 1` entries, for the rotation vector `w`
/// (length `gr`) of group `gr ≥ 2`: `Qᵀ = I − a Ω + b Ω²`.
#[inline(always)]
pub(crate) fn rotate_t<S: Scalar>(link: RotLink, gr: usize, w: &[S], x: &mut [S]) {
    let mut s2 = S::zero();
    for wi in w.iter().take(gr) {
        s2 += *wi * *wi;
    }
    let (a, b) = link_coeffs(link, s2);
    let xb = x[gr];
    let mut dot = S::zero();
    for i in 0..gr {
        dot += w[i] * x[i];
    }
    let f = a * xb + b * dot;
    for i in 0..gr {
        x[i] -= f * w[i];
    }
    x[gr] = xb + a * dot - b * s2 * xb;
}

/// `x ← Q_j x` on the first `gr + 1` entries: `Q = I + a Ω + b Ω²`.
#[inline(always)]
pub(crate) fn rotate<S: Scalar>(link: RotLink, gr: usize, w: &[S], x: &mut [S]) {
    let mut s2 = S::zero();
    for wi in w.iter().take(gr) {
        s2 += *wi * *wi;
    }
    let (a, b) = link_coeffs(link, s2);
    let xb = x[gr];
    let mut dot = S::zero();
    for i in 0..gr {
        dot += w[i] * x[i];
    }
    let f = a * xb - b * dot;
    for i in 0..gr {
        x[i] += f * w[i];
    }
    x[gr] = xb - a * dot - b * s2 * xb;
}

/// Log-eigenvalues along the axes (sum 0) into `ell[..d−1]`.
#[inline(always)]
fn log_eigen<S: Scalar>(gamma: &[S], d: usize, ell: &mut [S]) {
    let p = d - 1;
    let r = (gamma[0] * gamma[0] + gamma[1] * gamma[1]).sqrt();
    // asinh r = ln(r + √(1 + r²))
    let ar = (r + (r * r + 1.0).sqrt()).ln();
    ell[0] = S::zero() - ar;
    ell[1] = ar;
    for e in ell.iter_mut().take(p).skip(2) {
        *e = S::zero();
    }
    for gr in 2..=d - 2 {
        let off = gr * (gr + 1) / 2 - 1;
        let kappa = gamma[off];
        let n = (gr + 1) as f64;
        for e in ell.iter_mut().take(gr) {
            *e -= kappa * (1.0 / n);
        }
        ell[gr] += kappa * (gr as f64 / n);
    }
}

/// `y ↦` block coordinates `z` (length `≥ d`) and the quadratic form
/// `zᵀ W⁻¹ z`; returns `(t, y·μ, ‖μ‖², q_tangent)`.
#[inline(always)]
fn quad_form<S: Scalar>(
    fr: &GrFrame,
    mu: &[S],
    gamma: &[S],
    y: &[f64],
    z: &mut [S],
    scratch: &mut [S],
) -> (S, S, S, S) {
    let d = mu.len();
    let (t, ymu, mm) = project(&fr.lt, mu, y, z, scratch);
    turn(fr, z);
    let mut scale = S::one();
    let mut q = S::zero();
    for gr in (2..=d - 2).rev() {
        let off = gr * (gr + 1) / 2 - 1;
        let kappa = gamma[off];
        rotate_t(fr.link, gr, &gamma[off + 1..off + gr + 1], z);
        scale *= (kappa * (1.0 / (gr + 1) as f64)).exp();
        q += scale * (S::zero() - kappa).exp() * z[gr] * z[gr];
    }
    // Paine's block: W_2⁻¹ = √(1 + r²) I − [[g_1, g_2], [g_2, −g_1]]
    let (g1, g2) = (gamma[0], gamma[1]);
    let s = (g1 * g1 + g2 * g2 + 1.0).sqrt();
    let (x0, x1) = (z[0], z[1]);
    let q2 = s * (x0 * x0 + x1 * x1) - g1 * (x0 * x0 - x1 * x1) - g2 * (x0 * x1 * 2.0);
    q += scale * q2;
    (t, ymu, mm, q)
}

#[inline(always)]
fn loglik_core<S: Scalar>(
    fr: &GrFrame,
    mu: &[S],
    gamma: &[S],
    y: &[f64],
    z: &mut [S],
    scratch: &mut [S],
) -> S {
    let d = mu.len();
    let p = d - 1;
    let (t, ymu, mm, qt) = quad_form(fr, mu, gamma, y, z, scratch);
    let q = t * t + qt;
    let alpha = ymu / q.sqrt();
    S::from_f64(-0.5 * p as f64 * LN_2PI) - q.ln() * (0.5 * d as f64)
        + (alpha * alpha - mm) * 0.5
        + log_m_p(alpha, p)
}

/// Log-density at the unit vector `y` for stacked `eta = (mu, γ)`.
///
/// # Panics
/// If `eta.len()` is not [`dims::eta_len`] of `d = y.len()`, or the frame
/// has another dimension.
pub fn loglik_gr<S: Scalar>(fr: &GrFrame, eta: &[S], y: &[f64]) -> S {
    let d = y.len();
    assert_eq!(fr.dim(), d, "frame dimension {} but d = {d}", fr.dim());
    assert_eq!(eta.len(), dims::eta_len(d), "eta has length {}", eta.len());
    let (mu, gamma) = eta.split_at(d);
    match d {
        3 => fixed::<S, 3>(fr, mu, gamma, y),
        4 => fixed::<S, 4>(fr, mu, gamma, y),
        5 => fixed::<S, 5>(fr, mu, gamma, y),
        6 => fixed::<S, 6>(fr, mu, gamma, y),
        7 => fixed::<S, 7>(fr, mu, gamma, y),
        8 => fixed::<S, 8>(fr, mu, gamma, y),
        9 => fixed::<S, 9>(fr, mu, gamma, y),
        10 => fixed::<S, 10>(fr, mu, gamma, y),
        _ => {
            let (mut z, mut sc) = (vec![S::zero(); d], vec![S::zero(); d]);
            loglik_core(fr, mu, gamma, y, &mut z, &mut sc)
        }
    }
}

#[inline(always)]
fn fixed<S: Scalar, const D: usize>(fr: &GrFrame, mu: &[S], gamma: &[S], y: &[f64]) -> S {
    let (mut z, mut sc) = ([S::zero(); D], [S::zero(); D]);
    loglik_core(fr, mu, gamma, y, &mut z, &mut sc)
}

fn grad_dual<const N: usize>(fr: &GrFrame, eta: &[f64], y: &[f64], grad: &mut [f64]) -> f64 {
    let x: [Dual<N>; N] = seed_array(eta);
    let v = loglik_gr(fr, &x, y);
    grad.copy_from_slice(&v.eps);
    v.re
}

/// Log-density and its exact gradient in `eta` (forward mode).
///
/// # Panics
/// If `d` is outside `3..=10`, or as [`loglik_gr`].
pub fn loglik_gr_grad(fr: &GrFrame, eta: &[f64], y: &[f64], grad: &mut [f64]) -> f64 {
    match eta.len() {
        5 => grad_dual::<5>(fr, eta, y, grad),
        9 => grad_dual::<9>(fr, eta, y, grad),
        14 => grad_dual::<14>(fr, eta, y, grad),
        20 => grad_dual::<20>(fr, eta, y, grad),
        27 => grad_dual::<27>(fr, eta, y, grad),
        35 => grad_dual::<35>(fr, eta, y, grad),
        44 => grad_dual::<44>(fr, eta, y, grad),
        54 => grad_dual::<54>(fr, eta, y, grad),
        n => panic!("gamma-rot gradients are implemented for d = 3..=10 (eta length {n})"),
    }
}

/// Log-density, exact gradient and the Hessian in `eta` by central
/// differences of [`loglik_gr_grad`] (step `1e−5·max(1, |eta_i|)`,
/// symmetrised).
///
/// # Panics
/// As [`loglik_gr_grad`], or if `hess.len() != eta.len()²`.
pub fn loglik_gr_hess_fd(
    fr: &GrFrame,
    eta: &[f64],
    y: &[f64],
    grad: &mut [f64],
    hess: &mut [f64],
) -> f64 {
    let n = eta.len();
    assert_eq!(hess.len(), n * n, "hess must have length eta.len()²");
    let f = loglik_gr_grad(fr, eta, y, grad);
    let mut e = eta.to_vec();
    let (mut gp, mut gm) = (vec![0.0; n], vec![0.0; n]);
    for i in 0..n {
        let h = 1e-5 * eta[i].abs().max(1.0);
        e[i] = eta[i] + h;
        loglik_gr_grad(fr, &e, y, &mut gp);
        e[i] = eta[i] - h;
        loglik_gr_grad(fr, &e, y, &mut gm);
        e[i] = eta[i];
        for j in 0..n {
            hess[i * n + j] = (gp[j] - gm[j]) / (2.0 * h);
        }
    }
    for i in 0..n {
        for j in 0..i {
            let s = 0.5 * (hess[i * n + j] + hess[j * n + i]);
            hess[i * n + j] = s;
            hess[j * n + i] = s;
        }
    }
    f
}

#[cfg(test)]
